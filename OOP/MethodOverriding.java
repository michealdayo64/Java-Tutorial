public class MethodOverriding1{
	public static void main(String a[]){
	//System.out.println("Hello World");

	for(int i = 1; i < 13; i++){
		System.out.println(i + " Times Table");
		for(int j = 1; j < 13; j++){
			System.out.println(" " + i + " x " + j + " = " + (i * j));
}
		System.out.println("");
}
}
}