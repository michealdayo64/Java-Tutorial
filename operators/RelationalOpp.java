public class RelationalOpp{
    public static void main(String args[]){
        int num1 = 20;
        int num2 = 20;

        if(num1 > num2)
            System.out.println("Welcome");
        else if(num1 < num2)
            System.out.println("Hi");
        else if(num1 == num2)
            System.out.println("Hello");
        else
            System.out.println("Hello");
        
    }
}